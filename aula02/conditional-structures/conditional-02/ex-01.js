// exercise 01 - conditional 02

let color = "verde"

switch (color) {
    case "vermelho":
        console.log("Pare!");
        break
    case "amarelo":
        console.log("Atenção!");
        break
    case "verde":
        console.log("Pode passar!");
        break
    default:
        console.log("Cor desconhecida!");
}