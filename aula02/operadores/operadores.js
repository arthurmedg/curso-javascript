// Operadores Aritméticos
let a = 2
let b = 9

console.log("------ Operadores Aritméticos ------");

console.log(a + b); // Adição +
console.log(a - b); // Substração -
console.log(a * b); // Multiplicação *
console.log(a / b); // Divisão /
console.log(a % b); // Módulo
console.log(a ** b); // Potência **

// Operadores de Comparação
console.log("------ Operadores de Comparação ------");
let c = 7
let d = 8

console.log(c == d); // Comparação (Valor) ==
console.log(c === d); // Comparação Restrita (Valor e Tipo) ===
console.log(c != d); // Diferente !=
console.log(c !== d); // Diferença Restrita !=
console.log(c > d); // Maior >
console.log(c >= d); // Maior ou Igual >=
console.log(c < d); // Menor <
console.log(c <= d); // Menor ou Igual <=

